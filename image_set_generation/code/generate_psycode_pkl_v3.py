def resolve_paths(specs, working_dir, vhc_dir):
    """Find the full path for each image, using glob for BSDS/McGill."""
    for spec in specs:
        if spec['source'] == 'VHC':
            spec['path'] = os.path.join(vhc_dir, spec['filename'])
        else:
            # Search recursively under Original_Images/
            pattern = os.path.join(working_dir, 'Original_Images',
                                   '**', spec['filename'])
            matches = glob.glob(pattern, recursive=True)
            if len(matches) == 0:
                raise FileNotFoundError(
                    f"Could not find {spec['filename']} under Original_Images/")
            spec['path'] = matches[0]
    return specs


