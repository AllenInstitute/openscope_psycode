def main():
    os.chdir(WORKING_DIR)

    # --- Resolve all file paths ---
    print("Resolving source file paths...")
    resolve_paths(IMAGE_SPECS, WORKING_DIR, VHC_TEMP_DIR)

    print("\nVerifying source files exist:")
    all_ok = True
    for spec in IMAGE_SPECS:
        exists = os.path.isfile(spec['path'])
        tag = "OK" if exists else "MISSING"
        print(f"  {spec['pkl_name']}  {spec['source']:7s}  "
              f"{os.path.basename(spec['path'])}  [{tag}]")
        if not exists:
            all_ok = False
    if not all_ok:
        print("\nERROR: Some source files are missing. Aborting.")
        sys.exit(1)

    # ===== PASS 1: Load -> gamma decode -> crop -> compute target luminance =
    print("\n========== Pass 1: Computing target luminance ==========")
    cropped_images = {}
    all_ratios = []

    for spec in IMAGE_SPECS:
        name = spec['pkl_name']
        print(f"\n  [{name}]  {spec['source']}: {spec['filename']}")

        # 1. Load raw
        raw = load_img(spec['path'], spec['source'])
        print(f"    Raw shape: {raw.shape}  dtype: {raw.dtype}")

        # 2. Gamma decode (power 2.2 for BSDS/McGill, no-op for VHC)
        decoded = apply_gamma_decoding(raw, spec['source'])

        # 3. Crop edges + resize to prewarp size (918 x 1174)
        cropped = crop_raw_images(decoded)
        print(f"    Cropped shape: {cropped.shape}  dtype: {cropped.dtype}")

        cropped_images[name] = cropped

        # 4. Mean-to-max ratio
        ratio = get_mean_to_max_ratio(cropped)
        all_ratios.append(ratio)
        print(f"    Mean-to-max ratio: {ratio:.4f}")

    mean_ratio = np.median(all_ratios)
    target_luminance = np.uint8(255.0 * mean_ratio)
    print(f"\n  Median ratio across 8 images: {mean_ratio:.4f}")
    print(f"  >>> target_luminance = {target_luminance}")

    # ===== PASS 2: Luminance match -> 8-bit -> screen mask -> save =========
    print("\n========== Pass 2: Luminance matching & saving ==========")
    dict_image = {}

    for spec in IMAGE_SPECS:
        name = spec['pkl_name']
        print(f"\n  [{name}]")

        local_img = cropped_images[name].astype('float64')

        # 5. Fit scale to saturation
        local_img = fit_scale_to_saturation(
            local_img,
            target_luminance=target_luminance,
            target_saturation=2,
            apply_screen_mask=True,
        )

        # 6. Convert to uint8
        local_img = convert_8bit(local_img)

        # 7. Apply screen mask (outside -> 127)
        local_img = crop_prewarp_img(local_img)

        dict_image[name] = {}
        dict_image[name][name] = local_img

        print(f"    shape: {local_img.shape}  dtype: {local_img.dtype}  "
              f"range: [{local_img.min()}, {local_img.max()}]  "
              f"mean: {local_img.mean():.1f}")

    # --- Save pkl ---
    os.makedirs(os.path.dirname(OUTPUT_PKL), exist_ok=True)
    with open(OUTPUT_PKL, 'wb') as handle:
        pickle.dump(dict_image, handle, protocol=pickle.HIGHEST_PROTOCOL)
    print(f"\nSaved pkl -> {OUTPUT_PKL}")

    # --- Verify pkl ---
    print("\nVerifying saved pkl...")
    with open(OUTPUT_PKL, 'rb') as f:
        loaded = pickle.load(f)
    print(f"  Keys: {sorted(loaded.keys())}")
    for k in sorted(loaded.keys()):
        arr = loaded[k][k]
        print(f"  {k}: shape={arr.shape}  dtype={arr.dtype}  "
              f"range=[{arr.min()}, {arr.max()}]  mean={arr.mean():.1f}")

    # --- Create tiled preview ---
    print("\nCreating preview image...")
    fig, axes = plt.subplots(2, 4, figsize=(20, 10))
    sorted_names = sorted(dict_image.keys())
    for idx, name in enumerate(sorted_names):
        row, col = idx // 4, idx % 4
        ax = axes[row, col]
        ax.imshow(dict_image[name][name], cmap='gray', vmin=0, vmax=255)
        ax.set_title(name, fontsize=14)
        ax.axis('off')
    plt.suptitle(
        f'Psycode Set - Reprocessed from Raw Originals  '
        f'(target_luminance={target_luminance})',
        fontsize=16,
    )
    plt.tight_layout()
    plt.savefig(OUTPUT_PREVIEW, dpi=150, bbox_inches='tight')
    plt.close()
    print(f"Saved preview -> {OUTPUT_PREVIEW}")

    print("\n========== Done! ==========")


if __name__ == '__main__':
    main()
