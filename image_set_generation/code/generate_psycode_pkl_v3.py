# ---------- Image loading ----------

def read_from_img_file(path_file):
    """Load BSDS (.jpg) or McGill (.tif) as grayscale numpy array (uint8)."""
    img = Image.open(path_file)
    img = img.convert('L')
    return np.array(img)


def read_from_imc_raw_files(path_file):
    """Load VHC .imc binary file as uint16 numpy array (1024 x 1536).
    Original code provided by Michael Buice."""
    with open(path_file, 'rb') as im:
        s = im.read()
    arr = array.array('H', s)
    arr.byteswap()
    return np.array(arr, dtype='uint16').reshape(1024, 1536)


def load_img(path_file, database_source):
    """Load raw image based on database source."""
    if database_source in ('BSDS', 'McGill'):
        return read_from_img_file(path_file)
    elif database_source == 'VHC':
        return read_from_imc_raw_files(path_file)
    else:
        raise ValueError(f"Unknown database source: {database_source}")


# ---------- Gamma decoding ----------

def apply_gamma_decoding(img, database_source):
    """Apply gamma decoding: power 2.2 for BSDS/McGill, no-op for VHC."""
    if database_source in ('BSDS', 'McGill'):
        img = np.power(img.astype('float64'), 2.2)
    return img


# ---------- imresize replacement ----------

def _bytescale(data):
    """Replicate scipy.misc.bytescale: map [min, max] -> [0, 255] uint8."""
    cmin = float(data.min())
    cmax = float(data.max())
    cscale = cmax - cmin
    if cscale == 0:
        cscale = 1.0
    scale = 255.0 / cscale
    bytedata = (data.astype('float64') - cmin) * scale
    return (bytedata.clip(0, 255) + 0.5).astype(np.uint8)


def _imresize(arr, size):
    """Replicate scipy.misc.imresize(arr, size, interp='bilinear').

    Parameters
    ----------
    arr : ndarray
        Input image. If not uint8, bytescale is applied first
        (maps [min, max] to [0, 255]), matching original scipy behavior.
    size : tuple (height, width)
        Target size in numpy (row, col) convention.

    Returns
    -------
    ndarray uint8
        Resized image.
    """
    if arr.dtype != np.uint8:
        arr = _bytescale(arr)
    im = Image.fromarray(arr, mode='L')
    # PIL resize expects (width, height)
    im = im.resize((size[1], size[0]), Image.BILINEAR)
    return np.array(im)


# ---------- Cropping / resizing ----------

def crop_raw_images(data):
    """Crop to 16:10 aspect ratio and resize to prewarp size (918 x 1174).

    Replicates process_images.crop_raw_images exactly, replacing the
    deprecated scipy.misc.imresize with _imresize.
    """
    monitor_size = (1920, 1200)   # (width, height)
    warp_size = (1174, 918)       # (width, height)

    crop_x = int((monitor_size[0] - warp_size[0]) / 2)   # 373
    crop_y = int((monitor_size[1] - warp_size[1]) / 2)   # 141

    h, w = data.shape

    # Force 16:10 aspect ratio
    ratio_comparison = 10 * w - 16 * h
    if ratio_comparison > 0:
        excess = ratio_comparison / 10.0
        x = int(excess / 2.0)
        data = data[:, x:(w - x)]
    elif ratio_comparison < 0:
        excess = -ratio_comparison / 16.0
        x = int(excess / 2.0)
        data = data[x:(h - x), :]

    # Resize to full monitor size, then crop to warp area
    data = _imresize(data, size=(monitor_size[1], monitor_size[0]))
    data = data[crop_y:(monitor_size[1] - crop_y),
                crop_x:(monitor_size[0] - crop_x)]

    return data


# ---------- 8-bit conversion ----------

def convert_8bit(data):
    """Clip to [0, 255] and cast to uint8."""
    data[data >= 255] = 255
    data[data <= 0] = 0
    data = data.astype('uint8')
    return data


# ---------- Screen mask ----------

def get_screen_mask():
    """Allen Brain Observatory screen mask, cropped to prewarp size."""
    monitor_size = (1920, 1200)
    warp_size = (1174, 918)

    crop_x = int((monitor_size[0] - warp_size[0]) / 2)
    crop_y = int((monitor_size[1] - warp_size[1]) / 2)

    mask_screen = si.make_display_mask(display_shape=(1200, 1920))
    mask_screen = mask_screen[crop_y:(monitor_size[1] - crop_y),
                              crop_x:(monitor_size[0] - crop_x)]
    return mask_screen


def crop_prewarp_img(data, set_value=127):
    """Apply screen mask: set pixels outside the screen area to set_value."""
    mask_screen = get_screen_mask()
    data[mask_screen == 0] = set_value
    return data


# ---------- Saturation / luminance matching ----------

def get_percent_under_and_oversaturated_8bit(img):
    """Percentage of pixels that would be clipped at 0 or 255."""
    img = convert_8bit(img.copy())
    nb_sat = float(len(np.where(img == 255)[0]))
    nb_under_sat = float(len(np.where(img == 0)[0]))
    total_pix = len(img.flatten())
    return 100.0 * (nb_sat + nb_under_sat) / total_pix


def fit_scale_to_saturation(data, target_luminance=127,
                            target_saturation=2, apply_screen_mask=True):
    """Scale image so mean -> target_luminance, with at most
    target_saturation % of pixels clipped.

    Replicates process_images.fit_scale_to_saturation exactly.
    """
    local_img = data.astype('float64')

    if apply_screen_mask:
        mask_screen = get_screen_mask()
        list_pixel = local_img[mask_screen != 0].flatten()
    else:
        list_pixel = local_img.flatten()

    mean_img = np.mean(list_pixel)
    list_pixel = list_pixel - mean_img

    list_value_sorted = np.sort(np.unique(np.abs(list_pixel)))
    percent_sat = 0
    index = -1

    while percent_sat < target_saturation:
        scaling = float(target_luminance) / list_value_sorted[index]
        local_img_tmp = list_pixel * scaling + float(target_luminance)
        percent_sat = get_percent_under_and_oversaturated_8bit(local_img_tmp)
        index = index - 1

    if index == -2:
        index = -1
    else:
        index = index + 2

    scaling = float(target_luminance) / list_value_sorted[index]
    local_img = (local_img - mean_img) * scaling + float(target_luminance)

    return local_img


# ---------- Validation ----------

def get_mean_to_max_ratio(img, percentile=1):
    """Compute (mean - p_low) / (p_high - p_low) ratio."""
    mean_img = np.mean(img.flatten())
    max_img = np.percentile(img.flatten(), 100 - percentile)
    min_img = np.percentile(img.flatten(), percentile)
    return (mean_img - min_img) / (max_img - min_img)


